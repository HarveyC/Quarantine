def build(biome):
    comps = {"wall": wall_compounds, "port": port_compounds, "bore": bore_compounds}[biome]()
    parts = [MARK, f"; Lane parcels for {biome}: street (open lane with hook cover), compound (rooms, doors, chokes), roofline (height, perches).", ""]
    for p in streets() + comps + rooflines(biome):
        parts.append(p.render())
        parts.append("")
    parts.append(PLOTS.strip("\n"))
    parts += ["", "; Boss arenas (20x20): the boss fight's own ground, drawn to match its phases.", "\n\n".join(f().render() for f in ARENAS[biome])]
    return "\n".join(parts) + "\n"


for biome in ["wall", "port", "bore"]:
    path = os.path.join(ROOT, f"biome_{biome}.txt")
    text = open(path).read()
    if MARK in text:
        text = text[: text.index(MARK)]
    open(path, "w").write(text.rstrip("\n") + "\n\n" + build(biome))
    print("wrote", path)
