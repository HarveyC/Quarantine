"""Writes the lane parcels (street, compound, roofline) and lane plots into the three biome files.

The generator keeps these in a script because edge-wall parcels are drawn at double resolution
(9x9 characters for a 4x4 parcel) and are easy to get wrong by hand. Re-running replaces everything
after the LANES marker in each biome file.  python3 tools/gen_lane_parcels.py
"""
import os, re

MARK = "; ================================================================ LANES (generated by tools/gen_lane_parcels.py)"
ROOT = os.path.join(os.path.dirname(__file__), "..", "maps")


class P:
    """A 4x4 parcel. cell(x, y, ch); v(x, y, ch) = border east of cell (x, y), x = -1 is the west rim;
    h(x, y, ch) = border south of cell (x, y), y = -1 is the north rim."""

    def __init__(self, role, name, base="."):
        self.role, self.name = role, name
        self.c = [[base] * 4 for _ in range(4)]
        self.e = {}

    def cell(self, x, y, ch):
        self.c[y][x] = ch
        return self

    def fill(self, x0, y0, x1, y1, ch):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.c[y][x] = ch
        return self

    def v(self, x, y, ch="|"):
        self.e[(2 * x + 2, 2 * y + 1)] = ch
        return self

    def h(self, x, y, ch="-"):
        self.e[(2 * x + 1, 2 * y + 2)] = ch
        return self

    def vline(self, x, y0, y1, ch="|"):
        for y in range(y0, y1 + 1):
            self.v(x, y, ch)
        return self

    def hline(self, y, x0, x1, ch="-"):
        for x in range(x0, x1 + 1):
            self.h(x, y, ch)
        return self

    def box(self, x0, y0, x1, y1, ch_v="|", ch_h="-"):
        self.hline(y0 - 1, x0, x1, ch_h)
        self.hline(y1, x0, x1, ch_h)
        self.vline(x0 - 1, y0, y1, ch_v)
        self.vline(x1, y0, y1, ch_v)
        return self

    def uses_edges(self):
        return bool(self.e)

    def render(self):
        out = [f"@{self.role} {self.name}"]
        if not self.uses_edges():
            return "\n".join(out + ["".join(r) for r in self.c])
        for ry in range(9):
            row = []
            for rx in range(9):
                if ry % 2 == 1 and rx % 2 == 1:
                    row.append(self.c[ry // 2][rx // 2])
                elif ry % 2 == 0 and rx % 2 == 0:
                    row.append("+")
                else:
                    ch = self.e.get((rx, ry), " ")
                    # Compounds shut their street doors (opened by the first unit through); inner doors stay open.
                    if ch == "d" and self.role == "compound" and rx in (0, 8) or ch == "d" and self.role == "compound" and ry in (0, 8):
                        ch = "D"
                    row.append(ch)
            out.append("".join(row))
        return "\n".join(out)


