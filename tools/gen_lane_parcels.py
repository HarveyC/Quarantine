# ---------------------------------------------------------------- boss arenas (20x20, plain glyphs)
class A:
    """A 20x20 arena. P deploy, E enemy pod cells, B boss anchor (b: on an upper roof) (see maps/biome_wall.txt for glyphs)."""

    def __init__(self, name, boss=""):
        self.name = name
        self.boss = boss
        self.g = [["."] * 20 for _ in range(20)]

    def put(self, x, y, ch):
        if 0 <= x < 20 and 0 <= y < 20:
            self.g[y][x] = ch
        return self

    def rect(self, x0, y0, x1, y1, ch):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.put(x, y, ch)
        return self

    def ring(self, cx, cy, r0, r1, ch, keep=None):
        for y in range(20):
            for x in range(20):
                d = ((x - cx) ** 2 + (y - cy) ** 2) ** 0.5
                if r0 <= d <= r1 and (keep is None or self.g[y][x] == keep):
                    self.g[y][x] = ch
        return self

    def deploy(self):
        self.rect(8, 17, 11, 18, "P")
        for x, y in [(6, 16), (13, 16), (7, 19), (12, 19)]:
            self.put(x, y, "=")
        return self

    def pods(self, cells):
        for x, y in cells:
            self.put(x, y, "E")
        return self

    def render(self):
        return "\n".join([f"@arena {self.name} {self.boss}".rstrip()] + ["".join(r) for r in self.g])


